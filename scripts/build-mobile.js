// Packs the simulation (src/main: cat world, hero world, heroes, reminders, geometry) into one
// browser script for the phone app: node scripts/build-mobile.js [edition] → src/mobile/sim.js
// The modules are plain CommonJS; the few Node built-ins they touch (fs/path for desktop file
// names, os for diagnostics) get small stand-ins.
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const MODULES = [
  'main/geometry.js', 'main/names.js', 'main/world.js', 'main/ironman.js', 'main/reminders.js', 'main/editions.js', 'main/sysinfo.js',
  'main/heroes/index.js', 'main/heroes/homelander.js', 'main/heroes/hulk.js', 'main/heroes/spiderman.js', 'main/heroes/thor.js',
];
const edition = process.argv[2] || 'all';

let out = `/* generated by scripts/build-mobile.js — do not edit */\n(function (root) {\n'use strict';\nroot.BUDDY_EDITION = root.BUDDY_EDITION || ${JSON.stringify(edition)};\nconst defs = {};\n`;
for (const m of MODULES) {
  const code = fs.readFileSync(path.join(ROOT, 'src', m), 'utf8');
  out += `defs[${JSON.stringify(m)}] = function (module, exports, require) {\n${code}\n};\n`;
}
out += `
const SHIMS = {
  fs: { readdirSync() { throw new Error('no file system on the phone'); }, existsSync() { return false; } },
  path: { join: (...a) => a.join('/'), basename: (p) => String(p).split('/').pop() },
  os: { cpus: () => [], totalmem: () => 0, freemem: () => 0, uptime: () => (root.performance ? performance.now() / 1000 : 0), platform: () => 'android', loadavg: () => [0, 0, 0] },
};
const cache = {};
function resolve(from, p) {
  const parts = from.split('/').slice(0, -1);
  for (const seg of p.split('/')) {
    if (seg === '.' || seg === '') continue;
    if (seg === '..') parts.pop(); else parts.push(seg);
  }
  let id = parts.join('/');
  if (!/\\.js$/.test(id)) id += '.js';
  if (!defs[id] && defs[id.replace(/\\.js$/, '/index.js')]) id = id.replace(/\\.js$/, '/index.js');
  return id;
}
function load(id) {
  if (cache[id]) return cache[id].exports;
  if (!defs[id]) throw new Error('module not bundled: ' + id);
  const module = { exports: {} };
  cache[id] = module;
  defs[id](module, module.exports, (p) => (SHIMS[p] || load(resolve(id, p))));
  return module.exports;
}
root.BuddySim = { require: (id) => load(id) };
})(typeof window !== 'undefined' ? window : globalThis);
`;
const dest = path.join(ROOT, 'src', 'mobile', 'sim.js');
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out);
console.log(`wrote src/mobile/sim.js (${(out.length / 1024).toFixed(0)} KB, edition ${edition})`);
